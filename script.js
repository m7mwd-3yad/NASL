function openMobileMenu() {
    if (!mainNav || !mobileToggle) return;
    mainNav.classList.add('mobile-active');
    navBackdrop.classList.add('active');
    document.body.classList.add('menu-open');
    const icon = mobileToggle.querySelector('i');
    if (icon) {
        icon.className = 'fa-solid fa-xmark';
    }
    mobileToggle.setAttribute('aria-expanded', 'true');
}

function closeMobileMenu() {
    if (!mainNav || !mobileToggle) return;
    mainNav.classList.remove('mobile-active');
    navBackdrop.classList.remove('active');
    document.body.classList.remove('menu-open');
    const icon = mobileToggle.querySelector('i');
    if (icon) {
        icon.className = 'fa-solid fa-bars';
    }
    mobileToggle.setAttribute('aria-expanded', 'false');
}

if (mobileToggle && mainNav) {
    mobileToggle.addEventListener('click', (e) => {
        e.stopPropagation();
        if (mainNav.classList.contains('mobile-active')) {
            closeMobileMenu();
        } else {
            openMobileMenu();
        }
    });

    navBackdrop.addEventListener('click', closeMobileMenu);

    // Drawer internal close button handler
    const drawerCloseBtn = document.getElementById('mobileNavClose');
    if (drawerCloseBtn) {
        drawerCloseBtn.addEventListener('click', (e) => {
            e.stopPropagation();
            closeMobileMenu();
        });
    }

    document.querySelectorAll('.nav-link').forEach(link => {
        link.addEventListener('click', () => {
            closeMobileMenu();
        });
    });

    window.addEventListener('resize', () => {
        if (window.innerWidth > 768) {
            closeMobileMenu();
        }
    });
}

// --- 7. Sticky Header & Scroll Highlight ---
window.addEventListener('scroll', () => {
    const header = document.getElementById('header');
    if (header) {
        if (window.scrollY > 50) {
            header.classList.add('scrolled');
        } else {
            header.classList.remove('scrolled');
        }
    }

    const anchorNavLinks = document.querySelectorAll('.main-nav a[href^="#"]');
    if (anchorNavLinks.length > 0) {
        const sections = document.querySelectorAll('section[id]');
        const scrollY = window.pageYOffset;

        sections.forEach(current => {
            const sectionHeight = current.offsetHeight;
            const sectionTop = current.offsetTop - 120;
            const sectionId = current.getAttribute('id');
            const navLink = document.querySelector(`.main-nav a[href="#${sectionId}"]`);

            if (navLink) {
                if (scrollY > sectionTop && scrollY <= sectionTop + sectionHeight) {
                    document.querySelectorAll('.nav-link').forEach(l => l.classList.remove('active'));
                    navLink.classList.add('active');
                }
            }
        });
    }
});

